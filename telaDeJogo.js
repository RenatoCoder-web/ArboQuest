function telaDeJogo() {
    
    // ========================================================
    // INICIA MÚSICA DE BATALHA
    // ========================================================
    
    iniciarMusicaCombate();
    
    
    // ========================================================
    // RESET
    // ========================================================
    
    quest = [];
    
    memoryCash = [];
    
    memoryCashAlternativas = [];
    
    sequenciaAcoes = [];
    
    
    avancQuest =
        0;
    
    
    vidaPlayer =
        VIDA_MAXIMA;
    
    
    vidaEnemy =
        VIDA_MAXIMA;
    
    
    sequenciaAcertos =
        0;
    
    
    estrelaDisponivel =
        false;
    
    
    estrelaSelecionada =
        false;
    
    
    actionHero =
        '';
    
    
    proximo =
        true;
    
    
    gameFinished =
        false;

    totalRespostas = 0;
    totalAcertos = 0;
    totalErros = 0;
    defesaAtiva = false;
    resetMultiplayerStats();
    desempateParesDisponiveis = [];
    indiceDesempate = 0;
    emDesempate = false;
    
    
    // ========================================================
    // SELECIONA QUESTÕES - V8: PARES EQUIVALENTES
    // ========================================================

    function embaralharLista(lista) {
        for (var x = lista.length - 1; x > 0; x--) {
            var y = Math.floor(Math.random() * (x + 1));
            var tmp = lista[x]; lista[x] = lista[y]; lista[y] = tmp;
        }
        return lista;
    }

    function copiarEEmbaralharQuestao(q) {
        var alternativas = [
            [q[1][0], q[1][1]], [q[2][0], q[2][1]],
            [q[3][0], q[3][1]], [q[4][0], q[4][1]]
        ];
        embaralharLista(alternativas);
        return [q[0], alternativas[0], alternativas[1], alternativas[2], alternativas[3], q[5], q[6], q[7], q[8], q[9] || 'regular'];
    }

    function agruparPorPar(fonte, nivel) {
        var grupos = {};
        fonte.forEach(function(q) {
            if (q[5] !== nivel) return;
            var id = q[8];
            if (!grupos[id]) grupos[id] = [];
            grupos[id].push(q);
        });
        return Object.keys(grupos).map(function(id) { return grupos[id]; });
    }

    var paresRegulares = agruparPorPar(array, dificuldadeSelection);
    embaralharLista(paresRegulares);

    if (window.gameMode === 'multiplayer') {
        // Cada um dos 10 pares contém duas questões equivalentes.
        // Em cada rodada, uma vai para J1 e a outra para J2; a atribuição A/B é sorteada.
        paresRegulares.forEach(function(par) {
            var dupla = par.slice();
            embaralharLista(dupla);
            quest.push(copiarEEmbaralharQuestao(dupla[0])); // J1
            quest.push(copiarEEmbaralharQuestao(dupla[1])); // J2
        });

        // Banco independente de desempate: três pares por nível, em ordem aleatória.
        desempateParesDisponiveis = agruparPorPar(tieBreakArray, dificuldadeSelection);
        embaralharLista(desempateParesDisponiveis);
        desempateParesDisponiveis = desempateParesDisponiveis.map(function(par) {
            var dupla = par.slice();
            embaralharLista(dupla);
            return [copiarEEmbaralharQuestao(dupla[0]), copiarEEmbaralharQuestao(dupla[1])];
        });
        indiceDesempate = 0;
        emDesempate = false;
    } else {
        // Individual: uma questão sorteada de cada par equivalente = 10 questões equilibradas.
        paresRegulares.forEach(function(par) {
            var escolhida = par[Math.floor(Math.random() * par.length)];
            quest.push(copiarEEmbaralharQuestao(escolhida));
        });
        desempateParesDisponiveis = [];
        indiceDesempate = 0;
        emDesempate = false;
    }

    // ========================================================
    // VIDA
    // ========================================================
    
    atualizarBarrasDeVida();
    
    
    // ========================================================
    // ESTRELA
    // ========================================================
    
    atualizarEstrela();
    
    
    // ========================================================
    // CORREÇÃO
    // ========================================================
    
    esconderCorrecao();
    
    
    // ========================================================
    // POSICIONA ALTERNATIVAS
    // ========================================================
    
    for (
        let i = 0; i < 4; i++
    ) {
        
        // O posicionamento das alternativas é feito pelo CSS Grid responsivo.
        alterna[i].style.left = '';
        alterna[i].style.top = '';

        alterna[i]
            .spawnMsg
            .style.opacity =
            '1';
        
        
        // Evita acumular eventos.
        
        alterna[i].onclick =
            (function(indice) {
                
                return function() {
                    
                    responder(
                        indice
                    );
                };
                
            })(i);
    }
    
    
    // ========================================================
    // PRIMEIRA PERGUNTA
    // ========================================================
    
    carregarPergunta();
    
    
    console.log(
        'QUESTÕES:',
        quest
    );
    
    console.log(
        'SEQUÊNCIA:',
        sequenciaAcoes
    );
}


