// ============================================================
// ======================== RESPONDER ==========================
// ============================================================

function responder(
    indice
) {
    
    if (
        !proximo
    ) {
        return;
    }
    
    
    if (
        avancQuest >=
        quest.length
    ) {
        return;
    }
    
    
    if (
        actionHero === ''
    ) {
        return;
    }
    
    
    var perguntaAtual =
        quest[avancQuest];
    
    
    var respostaEscolhida =
        perguntaAtual[
            indice + 1
        ];
    
    
    // ========================================================
    // VERDADEIRO / FALSO
    // ========================================================
    
    var estaCerta =
        respostaEscolhida[1] ===
        true;
    
    
    valorResposta =
        estaCerta;
    
    
    proximo =
        false;

    totalRespostas++;
    if (estaCerta) {
        totalAcertos++;
    } else {
        totalErros++;
    }

    if (window.gameMode === 'multiplayer') {
        var jogadorDaRodada = jogadorAtual();
        var ehDesempate = perguntaAtual[9] === 'tiebreak';
        if (ehDesempate) {
            multiplayerStats[jogadorDaRodada].desempateRespostas++;
            if (estaCerta) multiplayerStats[jogadorDaRodada].desempateAcertos++;
            else multiplayerStats[jogadorDaRodada].desempateErros++;
        } else {
            multiplayerStats[jogadorDaRodada].respostas++;
            if (estaCerta) multiplayerStats[jogadorDaRodada].acertos++;
            else multiplayerStats[jogadorDaRodada].erros++;
            registrarCategoriaMultiplayer(jogadorDaRodada, perguntaAtual[7] || 'Conhecimentos gerais', estaCerta);
        }
    }
    
    
    var acao =
        actionHero;
    
    
    var usouEstrela =
        estrelaSelecionada &&
        estrelaDisponivel;
    
    
    // ========================================================
    // GUARDA SEQUÊNCIA
    // ========================================================
    
    sequenciaAcoes.push({
        
        pergunta: avancQuest,
        
        acao: acao,
        
        estrela: usouEstrela,
        
        resposta: estaCerta
    });
    
    
    // ========================================================
    // LIMPA ALTERNATIVAS
    // ========================================================
    
    for (
        var i = 0; i < 4; i++
    ) {
        
        alterna[i]
            .style.border =
            '';
        
        alterna[i]
            .style.backgroundColor =
            '';
        
        alterna[i]
            .style.color =
            '';
    }
    
    
    // ========================================================
    // ====================== CERTA ============================
    // ========================================================
    
    if (
        estaCerta
    ) {
        
        // Borda verde.
        
        alterna[indice]
            .style.border =
            '5px solid #00ff00';
        
        
        // Som de resposta certa.
        
        if (
            som[0]
        ) {
            
            som[0]
                .currentTime =
                0;
            
            som[0]
                .play()
                .catch(
                    function() {}
                );
        }
        
        
        // Conta acertos consecutivos.
        
        sequenciaAcertos++;
        
        
        // 3 certas = estrela.
        
        if (
            sequenciaAcertos >= 3 &&
            !estrelaDisponivel
        ) {
            
            liberarEstrela();
        }
        
        
        // ====================================================
        // ATAQUE + ESTRELA
        // ====================================================
        
        if (
            acao === 'ataque' &&
            usouEstrela
        ) {
            
            animarAtaquePlayer();
            causarDanoInimigo(
                DANO_ESPECIAL
            );
            
            consumirEstrela();
        }
        
        
        // ====================================================
        // DEFESA + ESTRELA
        // ====================================================
        
        else if (
            acao === 'defesa' &&
            usouEstrela
        ) {
            
            animarDefesaPlayer();
            curarPlayer(
                CURA_ESPECIAL
            );
            
            consumirEstrela();
        }
        
        
        // ====================================================
        // ATAQUE NORMAL
        // ====================================================
        
        else if (
            acao === 'ataque'
        ) {
            
            animarAtaquePlayer();
            causarDanoInimigo(
                DANO_NORMAL
            );
        }
        
        
        // ====================================================
        // DEFESA NORMAL
        // ====================================================
        
        else if (
            acao === 'defesa'
        ) {
            animarDefesaPlayer();
            defesaAtiva = true;
            console.log('🛡️ DEFESA ATIVA PARA O PRÓXIMO DANO');
        }
    }
    
    
    // ========================================================
    // ====================== ERRADA ===========================
    // ========================================================
    
    else {
        
        // Borda vermelha.
        
        alterna[indice]
            .style.border =
            '5px solid #ff0000';
        
        
        // Som de erro.
        
        if (
            som[1]
        ) {
            
            som[1]
                .currentTime =
                0;
            
            som[1]
                .play()
                .catch(
                    function() {}
                );
        }
        
        
        // Erro zera sequência.
        
        sequenciaAcertos =
            0;
        
        
        // ====================================================
        // ATAQUE + ERRO
        // PLAYER TOMA 20
        // ====================================================
        
        if (
            acao === 'ataque'
        ) {
            animarAtaqueInimigo();
            if (defesaAtiva) {
                defesaAtiva = false;
                animarDefesaPlayer();
                console.log('🛡️ DEFESA BLOQUEOU O DANO');
            } else {
                causarDanoPlayer(DANO_NORMAL);
            }
        }
        
        
        // ====================================================
        // DEFESA + ERRO
        // ESCUDO BLOQUEIA
        // ====================================================
        
        else if (
            acao === 'defesa'
        ) {
            animarAtaqueInimigo();
            if (defesaAtiva) {
                defesaAtiva = false;
                animarDefesaPlayer();
                console.log('🛡️ DEFESA ANTERIOR BLOQUEOU O DANO');
            } else {
                causarDanoPlayer(DANO_NORMAL);
            }
        }
    }
    
    
    // ========================================================
    // FEEDBACK CONTROLADO PELO JOGADOR/PROFESSOR
    // ========================================================
    mostrarCorrecao(perguntaAtual, estaCerta);


    // ========================================================
    // REMOVE EFEITO DE ATAQUE/DEFESA
    // Somente agora, depois que o resultado da resposta já foi
    // apresentado ao jogador (acerto/erro e suas consequências).
    // ========================================================
    
    if (typeof clearButtonEffects === 'function') {
        clearButtonEffects();
    }
    
    
    actionHero =
        '';
    
    
    estrelaSelecionada =
        false;
    
    
    atualizarEstrela();

    if (window.gameMode === 'multiplayer') {
        salvarEstadoJogadorMultiplayer();
    }
    
    
    // ========================================================
    // SE JÁ TERMINOU, NÃO AVANÇA
    // ========================================================
    
    if (gameFinished || (window.gameMode !== 'multiplayer' && (vidaPlayer <= 0 || vidaEnemy <= 0))) {
        return;
    }
    
    
    // ========================================================
    // PRÓXIMA QUESTÃO
    // ========================================================
    // Não há avanço automático. O feedback permanece disponível
    // para leitura e discussão até o clique em PRÓXIMA PERGUNTA.
}


